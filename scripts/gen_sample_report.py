GRID = colors.HexColor("#9bb2cc")
HEAD_BG = colors.HexColor("#1a3d6d")
ALT_BG = colors.HexColor("#eef3f9")


def make_table(rows: list[list[str]], styles, col_widths=None, padding=3):
    """构造带表头、斑马纹、网格的表格。

    ``padding`` 调大可以人为制造跨页表格，用于验证「跨页续表合并」逻辑。
    """
    head_style = styles["cell_head"]
    cell_style = styles["cell"]
    data = [[Paragraph(str(c), head_style) for c in rows[0]]]
    for r in rows[1:]:
        data.append([Paragraph(str(c), cell_style) for c in r])

    t = Table(data, colWidths=col_widths, repeatRows=1, hAlign="LEFT")
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEAD_BG),
        ("GRID", (0, 0), (-1, -1), 0.5, GRID),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), padding),
        ("BOTTOMPADDING", (0, 0), (-1, -1), padding),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
    ]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style.append(("BACKGROUND", (0, i), (-1, i), ALT_BG))
    t.setStyle(TableStyle(style))
    return t


