def _register_font() -> str:
    for name in ("STSong-Light", "STSongStd-Light"):
        try:
            pdfmetrics.registerFont(UnicodeCIDFont(name))
            return name
        except Exception:  # noqa: BLE001
            continue
    raise RuntimeError("未找到可用的中文字体")


